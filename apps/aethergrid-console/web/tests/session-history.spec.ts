import { test, expect } from '@playwright/test';
import { spawn, type ChildProcess } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import http from 'node:http';
import { hashPassword } from '../../security/session-runtime.mjs';
import { createObservationStore } from '../../observation-store.mjs';
let server: ChildProcess;
let dataDir: string;
let base: string;
let receipt: string;
let savedTimes: string[];
test.beforeAll(async () => {
 dataDir=await mkdtemp(join(tmpdir(),'aethergrid-browser-session-'));
 const probe=http.createServer();await new Promise<void>(resolve=>probe.listen(0,'127.0.0.1',resolve));
 const port=(probe.address() as {port:number}).port;await new Promise<void>(resolve=>probe.close(()=>resolve()));
 base=`http://127.0.0.1:${port}`;
 const record=await createObservationStore({dataDir}).record({kind:'weather',coordinate:{lat:40.7,lon:-74},observedAt:'2026-10-14T07:00:00Z',payload:{source:{provider:'browser-test-fixture',live:true},current:{temperatureC:20}}});receipt=record.receipt;
 savedTimes=[new Date(Date.now()-120000).toISOString(),new Date(Date.now()-60000).toISOString()];
 for(const [index,observedAt] of savedTimes.entries()) await createObservationStore({dataDir}).record({kind:'weather',coordinate:{lat:40.7549,lon:-73.984},observedAt,payload:{source:{provider:'browser-test-fixture',live:true,modelTime:observedAt,fetchedAt:observedAt,attribution:'BROWSER TEST RECORDING'},current:{time:observedAt,temperatureC:20+index,weatherCode:0}}});
 const users=[{username:'analyst',role:'Analyst',passwordHash:hashPassword('browser test password 123')}];
 server=spawn(process.execPath,['../server.mjs'],{env:{...process.env,AETHERGRID_AUTH_USERS:JSON.stringify(users),AETHERGRID_AUTH_REQUIRED:'1',AETHERGRID_DATA_DIR:dataDir,AETHERGRID_PORT:String(port)},stdio:'ignore'});
 for(let i=0;i<60;i++){try{if((await fetch(base+'/api/aethergrid/health')).ok) return;}catch{}await new Promise(resolve=>setTimeout(resolve,100));}
 throw new Error('Isolated authenticated runtime did not start');
});
test.afterAll(async()=>{server?.kill();await rm(dataDir,{recursive:true,force:true});});
test('canonical sign-in, recorded observation citation and sign-out',async({page})=>{
 await page.goto(base);
 await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
 await page.getByLabel('Username', {exact:true}).fill('analyst');
 await page.getByLabel('Password', {exact:true}).fill('browser test password 123');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByText('analyst · Analyst', {exact:true})).toBeVisible();
 const response=await page.request.get(base+'/api/aethergrid/weather/current?lat=40.7&lon=-74&at=2026-10-14T07%3A10%3A00Z');
 expect(response.status()).toBe(200);expect(response.headers()['x-aethergrid-observation']).toBe(receipt);
 await page.getByRole('navigation',{name:'Product modes'}).getByRole('button',{name:'GRID',exact:true}).click();
 const rail=page.getByRole('region',{name:'4D time controls'});
 await rail.getByRole('button',{name:'HISTORICAL',exact:true}).click();
 await expect(rail.getByRole('combobox',{name:'Recorded valid time'})).toBeEnabled();
 await rail.getByRole('combobox',{name:'Recorded valid time'}).selectOption(savedTimes[0]);
 await expect(page.locator('.weather-card')).toHaveAttribute('data-source-state','recorded');
 await expect(page.locator('.weather-card')).toContainText('20.0°C');
 const logoutResponse=page.waitForResponse(response=>response.url()===base+'/api/aethergrid/auth/logout');
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 expect((await logoutResponse).status()).toBe(200);
 await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
 expect((await page.request.get(base+'/api/aethergrid/state')).status()).toBe(401);
});
